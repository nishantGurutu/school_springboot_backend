-- Additive PostgreSQL migration for the school portal flows.
-- The application currently uses Hibernate ddl-auto=update, not a Flyway runner.
-- Review/apply in the deployment migration process; this file is not auto-executed.
ALTER TABLE certificates ADD COLUMN IF NOT EXISTS admission_no varchar(255);
ALTER TABLE fee_collections ADD COLUMN IF NOT EXISTS online_receipt varchar(255);
CREATE TABLE IF NOT EXISTS student_diary (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title varchar(255), content varchar(12000), class_name varchar(255), section varchar(255),
 target_student_id bigint, author_user_id bigint, file_url varchar(255), posted_at timestamp
);
CREATE TABLE IF NOT EXISTS portal_notifications (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint,
 title varchar(255), body varchar(12000), route varchar(255), reference_id varchar(255),
 created_at timestamp, read_at timestamp
);
CREATE INDEX IF NOT EXISTS idx_portal_notification_user ON portal_notifications(user_id,id DESC);
CREATE TABLE IF NOT EXISTS online_exams (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version bigint,
 title varchar(255), subject varchar(255), class_name varchar(255), section varchar(255),
 duration_minutes integer, opens_at timestamp with time zone, closes_at timestamp with time zone,
 published boolean NOT NULL, author_user_id bigint, questions_json varchar(100000)
);
CREATE TABLE IF NOT EXISTS online_exam_attempts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version bigint,
 exam_id bigint, student_id bigint, started_at timestamp with time zone, deadline timestamp with time zone,
 submitted_at timestamp with time zone, questions_json varchar(100000), answers_json varchar(100000),
 score integer, maximum integer, UNIQUE(exam_id,student_id)
);
CREATE TABLE IF NOT EXISTS fee_payments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, fee_id bigint, provider_id varchar(255) UNIQUE,
 reference varchar(255), checkout_url varchar(255), amount_minor bigint NOT NULL,
 paid_before_minor bigint NOT NULL, status varchar(255), receipt varchar(255),
 created_at timestamp with time zone, verified_at timestamp with time zone
);
CREATE TABLE IF NOT EXISTS push_devices (id varchar(255) PRIMARY KEY,user_id bigint,token varchar(4096));
CREATE INDEX IF NOT EXISTS idx_push_device_user ON push_devices(user_id);
CREATE TABLE IF NOT EXISTS push_deliveries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, notification_id bigint,device_id varchar(255),
 attempts integer NOT NULL,next_attempt_at timestamp with time zone,delivered_at timestamp with time zone,abandoned boolean NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_push_pending ON push_deliveries(abandoned,delivered_at,next_attempt_at);
